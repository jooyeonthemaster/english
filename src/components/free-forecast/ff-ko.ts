// 한국어 줄바꿈 금칙 — 보이는 글자는 그대로, 줄바꿈 자리만 막는다(사용자 요구 「이상하게 잘리지 않게」).
//   · 「·」「—」「→」「×」로 시작하는 줄       → 앞 공백을 줄바꿈 없는 공백(NBSP)으로, 붙인 「·」 앞에는 단어 결합자(WJ)
//   · 「〔보기〕⏎의」 닫는 괄호 뒤 조사         → 괄호와 조사 사이 WJ
//   · 「한⏎구간」「이⏎선생님」 한 글자 관형사 → 뒤 낱말에 NBSP 로 묶는다
//   · 「보내드릴⏎수 없습니다」「있을⏎때만」 의존명사 → 앞 낱말에 NBSP 로 묶는다
// 정규식에 lookbehind 를 쓰지 않는다(구형 iOS 인앱 브라우저는 정규식 생성 자체가 터진다).
// 시험: 작업 폴더(gitignore)의 ff-ko-test.mjs

export const WJ = "\u2060";
export const NB = "\u00a0";

// 줄 끝에 홀로 매달리면 어색한 낱말 — 한 글자 관형사·수사·부정어, 「어느」, 용언 관형형 「낼·할·볼·될」
// 「뒤」는 빼고 뒤로 묶는다(아래 의존명사 규칙) — 「6개월 뒤 모두」를 앞으로 묶으면 「6개월⏎뒤 모두」로 갈렸다
// 「다섯~아홉」「이번」 — 「앞 다섯⏎자리에」「이번⏎범위에」가 났다(3차 R3-11). 「이번엔」처럼 붙여 쓴 것은 공백이 없어 안 걸린다
const CLINGY = "한|두|세|네|이|그|저|빈|안|못|앞|첫|새|각|몇|전|총|약|매|어느|다섯|여섯|일곱|여덟|아홉|이번|낼|할|볼|될";
const RE_CLINGY = new RegExp(`(^|[\\s(「〔])(${CLINGY}) (?=[가-힣0-9])`, "g");

export function ko(text: string): string {
  const t = text
    .replace(/ ([·—→×])/g, `${NB}$1`)
    .replace(/× (?=\S)/g, `×${NB}`)
    .replace(/(\S)·/g, `$1${WJ}·`)
    .replace(/([〕」』)\]])(?=[가-힣])/g, `$1${WJ}`)
    .replace(/([가-힣A-Za-z0-9])\(/g, `$1${WJ}(`) // 「한글(HWP)」「10세트(정답」 — 붙인 여는 괄호 앞에서 끊기지 않게
    // 의존명사 — 뒤 낱말이 괄호·따옴표로 시작해도(「완성할 때 〔요약문〕의」), 조사가 붙어도(「있을 때만」「적절한 것을」) 앞 낱말에 묶는다.
    // 조사 목록 뒤에는 공백·문장부호·끝만 — 「때문에」「수능」「것이다」처럼 의존명사로 시작하는 다른 말은 건드리지 않는다
    .replace(/([가-힣]) (수|것|만큼|뿐|줄|후|때|뒤) (?=[가-힣0-9〔「『(\[])/g, `$1${NB}$2 `)
    .replace(/([가-힣]) (수|것|만큼|뿐|줄|후|때|뒤)(?=(?:만|도|은|는|이|가|에|을|를|까지|부터|마다|에도|에는)(?:\s|[.,!?)」』〕]|$))/g, `$1${NB}$2`)
    // 짧은 낫표 이름(10자 이하)은 한 덩어리 — 알림 「…신청서의 「무료로 받기!!!」를…」이 320·360 에서 「무료로⏎받기!!!」로 갈렸다(3차)
    .replace(/「([^「」]{1,10})」/g, (_m, inner: string) => `「${inner.replace(/ /g, NB)}」`);
  // 관형사 묶기는 겹치는 경우(「이 한 구간」)가 있어 두 번
  return t.replace(RE_CLINGY, `$1$2${NB}`).replace(RE_CLINGY, `$1$2${NB}`);
}
