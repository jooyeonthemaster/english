/** 글자 1개의 전진폭(em) — 정확한 글꼴 단위가 있으면 그것, 없으면 exam-font-metrics 규칙. */
export function explanationGlyphEm(ch: string, bold = false): number {
  const code = ch.charCodeAt(0);
  if (code >= 0x20 && code <= 0x7e && ch.length === 1) {
    return (bold ? ASCII_BOLD_UNITS : ASCII_UNITS)[code - 0x20] / UNITS_PER_EM;
  }
  const extra = EXTRA_UNITS[ch];
  if (extra) return extra[bold ? 1 : 0] / UNITS_PER_EM;
  return examGlyphEm(ch, bold);
}

export function explanationTextWidthPx(text: string, fontPx: number, bold = false): number {
  let em = 0;
  for (const ch of text) em += explanationGlyphEm(ch, bold);
  return em * fontPx;
}
