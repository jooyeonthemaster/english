const SPACE_EM = 0.3516;

const EXTRA_EM: Record<string, number> = {
  " ": SPACE_EM,
  "…": 0.7397, // …
  "‘": 0.231,
  "’": 0.231,
  "“": 0.3789,
  "”": 0.3789,
  "–": 0.5132,
  "—": 1.0259,
  "·": 0.2188,
};

function isFullWidth(code: number): boolean {
  return (
    (code >= 0x1100 && code <= 0x11ff) ||
    (code >= 0x2460 && code <= 0x24ff) || // ①~⑳ 등 원문자
    (code >= 0x3000 && code <= 0x9fff) ||
    (code >= 0xac00 && code <= 0xd7af) ||
    (code >= 0xff00 && code <= 0xffef)
  );
}

const EXTRA_BOLD_EM: Record<string, number> = {
  "…": 0.8823,
  "‘": 0.2793,
  "’": 0.2793,
  "“": 0.4717,
  "”": 0.4717,
  "·": 0.2617,
};

/** 글자 1개의 전진폭(em). 표에 없는 라틴 확장 문자는 소문자 평균(0.52)으로 본다. */
export function examGlyphEm(char: string, bold = false): number {
  const code = char.charCodeAt(0);
  if (code === 0x20) return SPACE_EM;
  if (code >= 0x21 && code <= 0x7e) return (bold ? ASCII_BOLD_EM : ASCII_EM)[code - 0x21];
  const extra = (bold ? EXTRA_BOLD_EM[char] : undefined) ?? EXTRA_EM[char];
  if (extra !== undefined) return extra;
  if (isFullWidth(code)) return 1;
  return bold ? 0.55 : 0.52;
}

/** 문자열 폭(px) — fontPx 크기의 시험지 본문 글꼴 기준(bold = 굵은꼴 면). */
export function examTextWidthPx(text: string, fontPx: number, bold = false): number {
  let em = 0;
  for (const ch of text) em += examGlyphEm(ch, bold);
  return em * fontPx;
}
