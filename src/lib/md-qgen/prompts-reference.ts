export const REFERENCE_MD_OPTION_LABELS = ["①", "②", "③", "④", "⑤"] as const;

// few-shot 해부 — 규칙 나열보다 실물 해부가 공예를 끌어올린다는 정본의 확정 결론.
// 지칭 추론의 격은 "최근접 명사가 문법으로는 완벽한데 논리로만 탈락하는가"에서 갈린다.
const REFERENCE_FEWSHOT = `## 모범 설계 해부 — 이 수준을 재현하라 (예시의 표현을 복사하지는 마라)
지문: 도시 계획가들이 주민의 반대에 부딪혀 계획을 고쳤고, 그때 모아 둔 반대 의견 기록이 훗날 다른 도시들에 재사용됐다는 글.
- 밑줄문장: The planners archived every objection they had collected, and later cities reused [[them]] to skip years of consultation.
- 표적 선정: them 은 바로 앞 명사구 cities 와 수가 같아 **문법으로는 완벽히 가능**하다. 그런데 "재사용해서 수년의 협의를 건너뛴다"는 논리는 도시가 아니라 앞 절의 목적어(모아 둔 반대 의견들)를 가리키게 만든다. 수·격 어느 것으로도 안 걸러지고 오직 논리로만 갈리는 자리다.
- 정답: "계획가들이 모아 둔 반대 의견들" — 앞 절의 목적어를 뒤 절의 목적어로 받는 주-목 전환 자리다.
- 오답 설계(기제 각 1개, 중복 없음): 최근접 명사 함정 — "훗날 등장한 다른 도시들"(바로 앞 주어, 수 일치). 역할 전도 — "계획을 세운 도시 계획가들"(반대 의견을 모은 주체, 같은 문장에 실재). 범위 이동 — "도시 계획 절차 전체"(실제 지칭보다 한 단계 넓음). 다른 마디의 주역 — "반대 의견을 낸 주민들"(앞 단락의 주역이지만 이 자리에서는 재사용 대상이 될 수 없음).
- 이 설계가 아름다운 이유: 네 오답이 전부 지문에 실재하는 명사구여서 지문을 안 읽고는 하나도 못 지운다. 문장 하나만 읽으면 최근접 명사가 가장 그럴듯하고, 앞 절의 목적어까지 되짚어야 판이 뒤집힌다.`;

// 표적(대명사) 설계 — 난이도 3분기. 프로덕션 난이도 루브릭과 정합.
const REFERENCE_TARGET_BY_DIFFICULTY: Record<MdDifficulty, string> = {
  BASIC: `## 표적 설계 (기본 난이도)
- 선행사가 **같은 문장 안 또는 바로 앞 문장**에 있고, 수(단수·복수)와 의미역이 한 번에 맞아떨어지는 대명사를 골라라(근거 깊이 1문장).
- 경쟁 명사구가 한둘뿐인 자리를 골라, 문장을 한 번 되짚으면 확정되게 하라.
- 지문 첫 문장의 대명사는 쓰지 마라 — 선행사가 지문 밖에 있을 수 있다.`,
  INTERMEDIATE: `## 표적 설계 (중급 난이도)
- 선행사와 대명사 사이에 **문장이 하나 이상 끼어 있는** 자리, 또는 같은 문장 안에 수·격이 모두 맞는 경쟁 명사구가 둘 이상인 자리를 골라라(근거 깊이 2문장).
- 지칭 해소가 **인과 또는 대조 연결**을 읽어야 확정되게 하라 — 가장 가까이 있다는 이유만으로 답이 정해지면 미달이다.
- 지문 첫 문장의 대명사는 쓰지 마라.`,
  KILLER: `## 표적 설계
- **최근접 명사가 문법적으로 완벽히 가능한데도 논리적으로는 불가능한 자리**를 노려라. 수 일치·격·어순 어느 것으로도 걸러지지 않고 오직 글의 논리로만 갈리는 대명사가 최고의 표적이다.
- 근거를 서로 다른 문장 두 개 이상에 흩어라 — 대명사가 든 문장 하나만 읽으면 최근접 명사가 정답처럼 보이고, 앞뒤 문장의 인과·대조를 읽어야 뒤집히는 구조.
- 앞 절의 목적어를 뒤 절의 주어·목적어로 받는 자리(주-목 전환), 대조절 뒤에서 앞 절의 비주역을 받는 자리를 우선하라.
- 지문 첫 문장의 대명사는 쓰지 마라.`,
};

function referenceExplanationBlock(mode: MdExplanationMode): string {
  const head = `정답: <①~⑤ 하나>
해설: <딱 2문장 — 첫 문장은 정답 선지의 문구를 작은따옴표로 그대로 인용해 지칭 대상을 단정하고, 둘째 문장은 근거가 되는 지문 문장을 인용해 수 일치·의미역·담화 흐름으로 확정한다. 합니다체`;
  if (mode === "answer-only") {
    return `${head}. 오답 해설은 쓰지 마라>`;
  }
  return `${head}>
오답:
① <기제이름 — 왜 매력적이고 왜 탈락인지 1문장> (정답 번호는 제외하고 오답 4개만)
...`;
}

/**
 * 지칭 추론 md 프롬프트.
 * 출력 계약(parser-reference.ts 와 1:1): `밑줄문장:` 한 줄(지문 축자 문장 + `[[대명사]]`
 * 마커 정확히 1개) + `①~⑤` 한국어 지칭 후보 + `정답:` + `해설:` + `오답:`.
 */
export function buildMdReferencePrompt(
  passage: string,
  mode: MdExplanationMode = "full",
  difficulty: MdDifficulty = "KILLER",
): string {
  const headline =
    difficulty === "KILLER"
      ? "아래 지문으로 '지칭 추론' KILLER 문항 1개를 설계하라. 선지 다섯 개 하나하나에 명확한 출제 의도가 박힌 아름다운 킬러 문항이어야 한다. 학생이 어느 후보에서 흔들릴지를 계산하고 학생 머리 꼭대기에서 설계하라."
      : `아래 지문으로 '지칭 추론' 문항 1개(난이도: ${difficulty === "BASIC" ? "기본 — 교과서 수준 확인형" : "중급 — 모의고사 중위권, 문맥 판단 필요"})를 설계하라. 선지 다섯 개 하나하나에 명확한 출제 의도가 있어야 한다.`;

  const fewshotBlock = difficulty === "BASIC" ? "" : `${REFERENCE_FEWSHOT}\n\n`;

  return `너는 대한민국 수능 영어영역을 20년 출제해 온 최정상 출제위원이다. ${headline}

${fewshotBlock}${REFERENCE_TARGET_BY_DIFFICULTY[difficulty]}

## 표적 자격 — 여기서 문항이 성립하거나 무효가 된다
- 표적은 **지문 안에 선행사가 실재하는 대명사 한 단어**여야 한다. 허용 목록: ${REFERENCE_PRONOUN_LIST.join(" · ")}.
- 🚫 허사 it 금지: it is/was ... that, it takes ... to 처럼 가리키는 대상이 아예 없는 it 을 표적으로 쓰면 문항이 성립하지 않는다.
- 🚫 한정사 용법 금지: this policy, these findings, those cities 처럼 뒤에 명사가 붙는 자리는 대명사가 아니라 한정사다. that 은 접속사·관계사로도 읽히니 표적으로 쓰지 마라(That is why ... 처럼 명백한 대명사 용법만 예외).
- 선행사는 **명사구**여야 한다. 문장 전체·절 전체를 받는 대명사(This means that ... 류)는 선지가 명사구로 떨어지지 않아 실격이다.
- 표적이 든 문장이 지문에 두 번 이상 나오면 밑줄 자리가 확정되지 않는다 — 그런 문장은 피하라.

## 오답 4개 — 기제 4종을 정확히 1개씩 (같은 기제 2개 금지)
1. **최근접 명사 함정**(최매력): 밑줄 대명사 **바로 앞**의 명사구. 위치로 보면 가장 자연스럽고 수·격까지 맞아, 그 문장 하나만 읽은 학생이 그대로 집는다.
2. **역할 전도**: 지칭 대상과 짝을 이루는 반대편(행위 주체 ↔ 그 행위를 당하는 쪽, 관찰자 ↔ 관찰 대상, 제공자 ↔ 수혜자). 같은 문장에 나란히 등장해 그럴듯하다.
3. **범위 이동**: 실제 지칭보다 한 단계 넓거나(개별 연구자들 → 학계 전체) 한 단계 좁은(제도 전체 → 그 제도의 한 조항) 명사구.
4. **다른 마디의 주역**: 지문의 다른 대목에서 논지를 지고 있어 이름값은 크지만, 이 대명사 자리에서는 담화 흐름상 후보가 될 수 없는 명사구.
- **소재 구속(절대)**: 다섯 선지는 전부 **지문에 실제로 등장하는 서로 다른 명사구**를 한국어로 옮긴 것이어야 한다. 지문에 없는 대상을 지어내면 학생이 지문 대조만으로 소거한다 — 그건 함정이 아니라 장식이다.
- 병렬 구조 함정을 최소 하나 넣어라: 대명사와 **수가 일치하고 문장에서 같은 역할**(주어끼리·목적어끼리)을 하는 명사구.
- **층위 일치**: 다섯 선지를 같은 층위의 명사구로 맞춰라. 사람 집단 하나에 추상 개념 넷을 섞으면 정답이 형태만으로 표난다.

## 마감 — 위반하면 시험 요령으로 뚫린다
- 즉사 오답 금지: 4개 중 최소 2개는 상위권 학생도 정답과 끝까지 저울질해야 한다. 수 불일치(복수 대명사에 단수 명사구)만으로 소거되는 선지를 3개 이상 만들지 마라.
- 선지에 **지칭 판정을 함께 적지 마라**: "'...' 문맥에서의 대명사 (다른 색들)" 처럼 괄호로 대상을 박거나 지문 위치를 설명하면 정답이 선지 텍스트에 그대로 노출된다. 선지는 후보 명사구 하나만 쓴다.
- 선지에 굵게·기울임·태그·번호·따옴표 강조를 붙이지 마라(서식은 서버가 넣는다). 특정 선지에만 서식이 붙으면 그 선지가 정답처럼 보이는 치명 결함이다.
- 선지 길이는 서로 비슷하게 — 가장 긴 선지가 가장 짧은 선지의 두 배를 넘기지 마라.
- 발문은 서버가 만든다. "나머지 넷과 다른 것은?" 같은 형식은 이 파이프라인이 만들 수 없으니 그런 문항을 설계하지 마라.

## 출력 전 자기검산 (사고 안에서 수행)
- 밑줄문장을 지문에서 **그대로 복사**했는지, 마커가 정확히 1개인지 확인하라 — 구두점·대소문자·축약형까지 원문과 같아야 하고, 마커는 대명사 한 단어만 감싼다.
- 그 문장이 지문에 두 번 이상 나오지 않는지 확인하라(반복되면 밑줄 자리가 유일하지 않다).
- 표적이 허사 it·한정사·접속사가 아닌지, 선행사가 지문 안 명사구인지 확인하라 — 아니면 표적 재선정.
- 다섯 선지 각각에 대해 "이 후보는 지문의 어느 명사구인가"를 한 줄씩 답해보라 — 못 대는 선지는 지문 밖에서 들여온 것이니 재설계.
- 오답 넷 각각에 대해 "이 학생은 왜 이걸 고르는가"를 한 줄씩 답해보라 — 못 대면 기제 재설계. 기제가 겹치는 오답이 없는지도 확인하라.
- **해설 첫 문장에 정답 선지의 문구를 작은따옴표로 그대로 인용했는지** 확인하라(선지 텍스트와 한 글자도 다르지 않게). 해설이 논증한 대상과 \`정답:\` 라벨이 어긋나는 것이 이 유형의 최다 결함이다.
- 오답 목록에 정답 번호를 절대 포함하지 마라.
- 해설은 한국어만 쓴다(영단어를 한국어 문장의 어휘로 섞지 마라 — 지문 표현 인용만 허용).

## 밑줄문장 작성 규칙 (기계 파싱 계약)
- 한 줄에 문장 하나. 표적 대명사만 \`[[them]]\` 처럼 이중 대괄호로 감싼다. 라벨·번호를 붙이지 마라.
- 마커는 정확히 **1개**다. 지문의 다른 부분을 함께 옮기거나 마커를 두 개 이상 찍지 마라.
- 마커 밖 글자는 원문 그대로다. 요약·축약·구두점 교체 금지.

## 출력 형식 (마크다운 — 이 형식 그대로, 다른 말 붙이지 마라)
밑줄문장: <표적 대명사가 든 지문 문장 하나를 한 글자도 바꾸지 말고 한 줄로 옮겨 적되, 표적 대명사 한 곳만 [[them]] 처럼 감싼다>
① <한국어 지칭 대상 후보 — 지문에 실재하는 명사구를 옮긴 것>
② <한국어 지칭 대상 후보>
③ <한국어 지칭 대상 후보>
④ <한국어 지칭 대상 후보>
⑤ <한국어 지칭 대상 후보>
${referenceExplanationBlock(mode)}

## 지문
${passage}`;
}
