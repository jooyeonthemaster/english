export const SENTENCE_INSERT_MD_CIRCLED = [
  "①", "②", "③", "④", "⑤", "⑥", "⑦", "⑧",
] as const;

export const SENTENCE_INSERT_MD_SLOT_MIN = 5;
export const SENTENCE_INSERT_MD_SLOT_MAX = 8;

/** 자리 개수 클램프 — UI 범위(5~8, "삽입 위치 마커 수")와 동기. */
export function clampInsertMdSlotCount(value: unknown): number {
  const n = Math.round(Number(value));
  if (!Number.isFinite(n)) return SENTENCE_INSERT_MD_SLOT_MIN;
  return Math.min(
    SENTENCE_INSERT_MD_SLOT_MAX,
    Math.max(SENTENCE_INSERT_MD_SLOT_MIN, n),
  );
}

