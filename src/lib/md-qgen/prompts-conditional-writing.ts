function conditionalWritingOutputBlock(
  mode: MdExplanationMode,
  difficulty: MdDifficulty,
): string {
  const minConditions = CW_MD_CONDITION_MIN[difficulty];
  // ⚠ 인용 규칙을 무조건형("영어 표현은 반드시 작은따옴표로")으로 두면, KILLER 표적 설계가
  //   권장하는 구문명(not only A but also B 류)까지 인용돼 게이트 #9 가 자동 반려한다
  //   (프롬프트 지시와 게이트 판정이 서로를 배제하는 자기모순 — wave2 실측).
  const conditionScaffold = Array.from({ length: Math.max(2, minConditions) }, (_, i) =>
    i === 0
      ? "- <조건 1 — 학생이 답안에 문자 그대로 써야(또는 쓰지 말아야) 하는 표현만 작은따옴표로 감쌀 것. 구문·문법 용어에는 따옴표 금지>"
      : `- <조건 ${i + 1}>`,
  ).join("\n");

  const criteriaBlock =
    mode === "answer-only"
      ? ""
      : `채점기준:
- <채점 항목 1 — 무엇을 확인해 몇 점인지>
- <채점 항목 2>
`;

  return `우리말: <표적 문장의 한국어 번역 한 줄. 영어 금지. 원문의 의미 범위와 1:1>
조건:
${conditionScaffold}
모범답안: <조건을 전부 만족하는 영어 완성 문장 한 줄>
${criteriaBlock}해설: <딱 2문장 — ① 각 조건이 모범답안의 어느 부분에서 어떻게 충족되는지 ② 원문 대비 어떤 시제·태·구문 전환을 썼는지. 합니다체>`;
}

/**
 * 조건부 영작 md 프롬프트.
 * 출력 계약(parser-conditional-writing.ts 와 1:1): `우리말:` 한 줄 +
 * `조건:` 불릿 목록 + `모범답안:` 한 줄 + `채점기준:` 불릿 목록 + `해설:`.
 *
 * ⚠ `정답:` 줄이 없다 — 모범답안이 정답의 유일 진실원이다(§1-B 철칙 1).
 *   어댑터가 correctAnswer = modelAnswer 로 복제하므로 같은 사실을 두 번 받지 않는다.
 */
export function buildMdConditionalWritingPrompt(
  passage: string,
  mode: MdExplanationMode = "full",
  difficulty: MdDifficulty = "KILLER",
): string {
  const headline =
    difficulty === "KILLER"
      ? "아래 지문에서 논지를 지고 있는 문장 하나를 골라, 그 한국어 번역과 작성 조건을 제시하고 학생이 영어로 영작하게 하는 KILLER 서술형 문항 1개를 설계하라. 조건 하나하나에 명확한 출제 의도가 박힌 아름다운 킬러 문항이어야 한다. 학생이 어느 구문에서 무너질지를 계산하고 학생 머리 꼭대기에서 설계하라."
      : `아래 지문에서 논지를 지고 있는 문장 하나를 골라, 그 한국어 번역과 작성 조건을 제시하고 학생이 영어로 영작하게 하는 서술형 문항 1개(난이도: ${difficulty === "BASIC" ? "기본 — 교과서 수준 확인형" : "중급 — 모의고사 중위권, 구문 전환 필요"})를 설계하라. 조건 하나하나에 명확한 출제 의도가 있어야 한다.`;

  const fewshotBlock = difficulty === "BASIC" ? "" : `${CW_FEWSHOT}\n\n`;

  return `너는 대한민국 수능·내신 영어 서술형을 20년 출제해 온 최정상 출제위원이다. ${headline}

${fewshotBlock}## 표적 문장 선정 — 여기서 문항의 격이 갈린다
- 표적은 지문의 **논지를 담지한 문장**이어야 한다. 예시 나열·수치 부연·장식 수식만 있는 문장은 실격이다.
- 그 문장 하나만으로 명제가 완결돼야 한다. 앞 문장의 대명사(this·such·they)에 기대는 문장을 고르면, 한국어로 옮기는 순간 지시 대상이 사라져 학생이 무엇을 쓸지 알 수 없다.
- 우리말은 원문의 **의미 범위와 1:1**이어야 한다. 원문의 절·수식어를 임의로 잘라내면 학생 답과 모범답안의 길이가 어긋나 채점이 붕괴한다.
- 우리말은 자연스러운 한국어 한 문장으로 써라. 영어 어순을 그대로 옮긴 번역투는 학생이 무엇을 요구받는지 알 수 없게 만든다.

${CW_TARGET_BY_DIFFICULTY[difficulty]}

${CW_CONDITION_TAXONOMY}

${CW_CLOSING}

${CW_SELF_CHECK}

## 출력 형식 (마크다운 — 이 형식 그대로, 다른 말 붙이지 마라)
${conditionalWritingOutputBlock(mode, difficulty)}

## 지문
${passage}`;
}
