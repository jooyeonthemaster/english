export const SENTENCE_ORDER_MD_LABELS = ["A", "B", "C"] as const;

export const SENTENCE_ORDER_MD_CIRCLED = ["①", "②", "③", "④", "⑤"] as const;

export const SENTENCE_ORDER_MD_PREFIX_VARIATION_MIN = 0;
export const SENTENCE_ORDER_MD_PREFIX_VARIATION_MAX = 3;

/** 변형할 단락 수 클램프 — UI 범위(0~3, "앞문장 변형 문단 수")와 동기. */
export function clampOrderMdPrefixVariationCount(value: unknown): number {
  const n = Math.round(Number(value));
  if (!Number.isFinite(n)) return SENTENCE_ORDER_MD_PREFIX_VARIATION_MIN;
  return Math.min(
    SENTENCE_ORDER_MD_PREFIX_VARIATION_MAX,
    Math.max(SENTENCE_ORDER_MD_PREFIX_VARIATION_MIN, n),
  );
}

