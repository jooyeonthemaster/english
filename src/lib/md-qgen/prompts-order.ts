function paragraphVariationSection(count: number): string {
  if (count <= 0) return "";
  const targets = SENTENCE_ORDER_MD_LABELS.slice(0, count)
    .map((l) => `(${l})`)
    .join("");
  return `## 단락 첫 문장 변형 (교사 설정, 필수 — 위 '축자' 지시의 유일한 예외다)
- 목적은 하나다. 지문을 이미 본 학생은 단락을 통째로 외워 **표면 대조만으로** 순서를 복원한다. 외운 것은 (A)(B)(C) 단락이므로 변형도 단락에 건다.
- 대상은 라벨 순서대로 **앞에서 ${count}개 단락 — ${targets}** 이다. 무작위로 고르지 말고 (A)부터 차례로 적용하라.
- 대상 단락은 **두 줄**로 낸다. \`단락(X):\` 는 지문 축자 그대로(서버가 이 줄로 무손실 분할과 정답 순서를 검산한다), \`단락(X,변형):\` 은 학생에게 보이는 본문이다. 두 줄이 모두 있어야 한다.
- 변형은 그 단락의 **첫 문장에만** 적용한다. 2번째 문장부터는 축자 줄과 **한 글자도 다르지 않게** 그대로 이어 붙여라 — 기계가 뒷부분을 문자 단위로 대조한다.
- 🚫 \`주어진글:\` 은 **절대 변형하지 마라.** 어떤 설정에서도 지문 맨 앞 축자 그대로다.
- 🚫 변형 대상이 아닌 단락은 변형 줄을 만들지 마라. ${count < 3 ? `${SENTENCE_ORDER_MD_LABELS.slice(count).map((l) => `(${l})`).join("")} 는 축자 한 줄뿐이다.` : ""}
- 🚫 절대 불변 — **위치를 결정하는 단서**: 먼저 그 첫 문장에서 단락의 자리를 결정하는 논리 단서를 **하나** 특정하라(However=역접, Therefore=인과, For example=예시, this/such/that+명사=앞 내용 되받기, then/later/in turn=시간 순서). 주변 표현은 바꾸되 그 단서의 **종류와 방향**은 그대로 두고, 되받는 지시 대상은 **같은 선행어**를 가리켜야 한다. 단서가 여럿이면 최소한 자리를 결정하는 그것만은 반드시 남겨라(역접·인과·예시·되받기가 있으면 그중 하나는 필수다). 단서를 지우면 정답이 여러 개가 되어 문항이 죽는다. 정답 순열과 (A)(B)(C) 라벨은 바뀌지 않는다.
- 🚫 **방향을 뒤집지 마라**: later↔earlier, then↔initially, therefore↔because of this 처럼 종류가 같아도 방향이 반대면 학생이 보는 면이 정답과 **반대 순서**를 지시한다(기계가 방향까지 대조한다).
- 🚫 **되받는 대상을 바꾸지 마라**: 'those remarks'(앞 단락의 논평) 를 'those copying errors'(주어진 글의 오류) 로 바꾸면 두 단어 교체로 다른 배열도 성립해 복수정답이 된다. 지시 명사구는 축자와 **같은 조각**을 가리켜야 한다.
- 🚫 첫 문장에 연결사도 지시사도 없이 **앞 조각과 같은 핵심어**로만 이어지는 경우가 있다. 그 어휘 사슬이 유일한 자리 근거이므로, 재진술하면서 그 핵심어를 전부 동의어로 갈아 치우지 마라 — 최소 하나는 남긴다.
- 🚫 anti-aliasing 자기검사: 변형한 뒤 **다른 배열도 말이 되는지** 스스로 다시 풀어 보라. 변형된 첫 문장 때문에 그 단락이 두 자리 이상에 들어맞게 됐으면 더 가벼운 변형으로 되돌려라. 의도한 순서가 **유일한** 정답으로 남아야 한다.
- 🚫 다음은 전부 반려다: (1) 축자 첫 문장을 그대로 복사(변형이 아니다), (2) 지문의 다른 구간을 옮겨 적기, (3) 다른 단락을 재진술한 문장 — 기계가 "자기 축자 첫 문장과 겹치는 내용어 vs 다른 단락과 겹치는 내용어"를 세어 무엇의 재진술인지 판정한다, (4) 축자 첫 문장과 공통 내용어가 없는 무관한 문장, (5) 영어가 아닌 문장(한글을 한 글자라도 섞지 마라), (6) 한 문장을 여러 문장으로 늘리기, (7) 축자 첫 문장을 **그대로 둔 채** 앞뒤에 문장·구를 덧붙이기 — 외운 문장이 그대로 남아 목적이 무너진다, (8) 변형본 앞에 순서 번호(1. / ②)나 (A)(B)(C) 라벨 적기.
- 변형된 첫 문장은 **정확히 1문장**이고 반드시 마침표(또는 ?!)로 끝난다. 분량은 축자 첫 문장의 **0.6~1.7배 단어 수** 안에서 유지한다. 같은 뜻을 다시 쓰는 것이므로 핵심 명사 두엇은 자연히 겹친다 — 주제어까지 갈아 끼워 다른 문장이 되면 반려다.
- 변형 뒤의 **학생이 보는 분량**도 계약이다: 세 단락 각각 24단어 이상, 가장 긴 쪽 ÷ 가장 짧은 쪽 1.9 이하. 한 단락의 첫 문장만 크게 늘리거나 줄이면 축자가 균형이어도 표시면이 무너져 분량으로 답이 드러난다.
- 위 '공짜 소거 금지' 규칙은 변형본에도 그대로 적용된다. 재진술하면서 문장 앞에 연결사·지시 명사구를 **새로 붙이지 마라**(정답 배열의 첫 단락만 예외).`;
}

function orderExplanationBlock(mode: MdExplanationMode): string {
  const head = `정답: <①~⑤ 하나>
해설: <딱 2문장 — 이음매마다 어떤 응집장치(지시사·연결사·시간 표지·어휘 사슬)가 순서를 확정하는지 지목. 합니다체`;
  if (mode === "answer-only") {
    return `${head}. 오답 해설은 쓰지 마라>`;
  }
  return `${head}>
오답:
① <이 배열이 어느 이음매에서 무엇 때문에 깨지는지 1문장> (정답 번호는 제외하고 오답 4개만)
...`;
}

